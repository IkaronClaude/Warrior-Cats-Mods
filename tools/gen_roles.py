"""Generates mod/WaCaModKit/Scripts/wacaroles.lua (enum name <-> value tables) from the UE4SS C++ header dump.
python tools/gen_roles.py dumps/CXXHeaderDump"""
import re, sys, pathlib
dump = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "dumps/CXXHeaderDump")
wanted = {"ENarrativeRole": "SwtQuest_enums.hpp", "EGiverRole": "SwtQuest_enums.hpp", "EClanType": "SwtQuest_enums.hpp"}
import glob
for extra in ("EPatternType", "EMarkingType"):
    for f in glob.glob(str(dump / "*_enums.hpp")):
        if ("enum class %s {" % extra) in open(f, encoding="utf-8").read():
            wanted[extra] = pathlib.Path(f).name
out = ["-- generated by tools/gen_roles.py from the game's enums (names <-> values); do not edit", "return {"]
for enum, fname in wanted.items():
    text = (dump / fname).read_text(encoding="utf-8")
    body = re.search(r"enum class %s \{(.*?)\};" % enum, text, re.S).group(1)
    pairs = re.findall(r"(\w+) = (\d+)", body)
    out.append("    %s = {" % enum)
    for name, val in pairs:
        if name.endswith("_MAX") or name in ("Total",):
            continue
        out.append("        %s = %s," % (name, val))
    out.append("    },")
out.append("}")
pathlib.Path("mod/WaCaModKit/Scripts/wacaroles.lua").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print("wrote", sum(1 for l in out if "=" in l and "{" not in l), "values")
