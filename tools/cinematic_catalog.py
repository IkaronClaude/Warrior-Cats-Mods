"""A catalog of the game's own cinematic building blocks - what a text cutscene can reuse (tickets.md "Cutscenes from
text": no 3D work, mix and match the game's pieces). Reads the game's file list (dumps/files.txt - a listing of the
game's paks, made locally; BYO, not in git) and writes a grouped Markdown catalog (local output - asset NAMES come from
the game, so the catalog is not committed):

    python tools/cinematic_catalog.py dumps/files.txt <out.md>

Groups: level sequences (by their name's first parts), cat montages and animations by action word (idle, sit, walk,
angry, hiss, sleep, groom, ...), per-character cinematic poses, camera assets, Niagara emote-like effects.
"""
import re
import sys
from collections import defaultdict

ACTIONS = ["idle", "sit", "lie", "sleep", "awake", "walk", "run", "trot", "jump", "pounce", "crouch", "sneak", "angry",
           "hiss", "growl", "bristl", "happy", "sad", "surprise", "fear", "scared", "groom", "lick", "stretch", "yawn",
           "nod", "shake", "talk", "greet", "headbutt", "nuzzle", "purr", "eat", "drink", "dig", "climb", "swim",
           "attack", "hit", "dodge", "lose", "win", "victory", "defeat", "die", "death", "look", "turn", "ceremony",
           "bow", "howl", "call", "play", "pose", "cinematic", "emote"]


def main():
    src, out = sys.argv[1], sys.argv[2]
    names = [l.strip() for l in open(src, encoding="utf-8", errors="replace") if l.strip().endswith(".uasset")]
    seqs = defaultdict(list)
    montages = defaultdict(list)
    anims = defaultdict(list)
    poses = defaultdict(list)
    cameras, effects = [], []
    for path in names:
        base = path.rsplit("/", 1)[-1][:-len(".uasset")]
        low = base.lower()
        if base.startswith("LS_") or "/Cinematics/" in path and base.startswith(("LS", "Seq")):
            parts = base.split("_")
            seqs["_".join(parts[1:3]) if len(parts) > 2 else base].append(base)
        elif base.startswith("AM_") and ("cat" in low or "/Characters/Cat" in path):
            word = next((w for w in ACTIONS if w in low), "other")
            montages[word].append(base)
        elif base.startswith("A_") and "/Characters/Cat" in path:
            m = re.match(r"A_([A-Z][a-z]+)_(.+)$", base)
            if m and m.group(1) not in ("CatMaster", "Cat"):
                poses[m.group(1)].append(base)
            else:
                word = next((w for w in ACTIONS if w in low), "other")
                anims[word].append(base)
        elif "camera" in low and ("/Cinematics/" in path or base.startswith(("BP_", "CS_", "CameraShake", "CA_"))):
            cameras.append(base)
        elif base.startswith("NS_") and any(w in low for w in ("emote", "anger", "heart", "sweat", "exclam", "question", "zzz", "tears", "sparkle")):
            effects.append(base)
    with open(out, "w", encoding="utf-8") as f:
        f.write("# The game's cinematic building blocks (generated by tools/cinematic_catalog.py - local, not in git)\n\n")

        def section(title, groups):
            total = sum(len(v) for v in groups.values()) if isinstance(groups, dict) else len(groups)
            f.write("## %s (%d)\n\n" % (title, total))
            if isinstance(groups, dict):
                for k in sorted(groups, key=lambda k: (-len(groups[k]), k)):
                    f.write("- **%s** (%d): %s\n" % (k, len(groups[k]), ", ".join(sorted(groups[k]))))
            else:
                f.write(", ".join(sorted(groups)) + "\n")
            f.write("\n")
        section("Level sequences, by kind", seqs)
        section("Cat montages, by action", montages)
        section("Cat animations, by action", anims)
        section("Per-character cinematic poses", poses)
        section("Camera assets", cameras)
        section("Emote-like effects", effects)
    print("wrote %s: %d sequence kinds, %d montages, %d animations, %d characters with poses, %d cameras, %d effects" % (
        out, len(seqs), sum(map(len, montages.values())), sum(map(len, anims.values())), len(poses), len(cameras), len(effects)))


if __name__ == "__main__":
    main()
