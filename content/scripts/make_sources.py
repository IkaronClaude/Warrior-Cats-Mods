"""Generates the WaCa content's source files (no third-party assets): content/source/

  python content/scripts/make_sources.py

- SM_WaCaPrecipCylinder.obj: an open cylinder, radius 100, height 200 (centred), 48 sides, UV u = around (0..1 per
  turn), v = 0 at the top -> 1 at the bottom. The weather's falling streaks are drawn on it by the material; the mod
  scales copies of it around the cat.
- SW_WaCaRainLoop.wav: 12 s of synthesized rain (filtered noise + random drop ticks), seamless when looped
  (the end crossfades into the start), mono 16-bit 44.1 kHz.
"""
import math
import os
import wave

import numpy as np

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "source")
os.makedirs(out, exist_ok=True)

# --- the cylinder -------------------------------------------------------------------------------------------------
SIDES, R, H = 48, 100.0, 200.0
lines = ["# WaCa ModKit weather cylinder (generated by content/scripts/make_sources.py)"]
for i in range(SIDES + 1):                       # the seam's column repeated so u runs 0..1
    a = 2 * math.pi * i / SIDES
    x, y = R * math.cos(a), R * math.sin(a)
    lines.append(f"v {x:.4f} {y:.4f} {H / 2:.4f}")
    lines.append(f"v {x:.4f} {y:.4f} {-H / 2:.4f}")
    lines.append(f"vt {i / SIDES:.6f} 0.0")      # OBJ v is bottom-up: the importer flips it -> 0 at the top
    lines.append(f"vt {i / SIDES:.6f} 1.0")
    lines.append(f"vn {-math.cos(a):.6f} {-math.sin(a):.6f} 0.0")    # inward: seen from inside (two-sided anyway)
for i in range(SIDES):
    t0, b0, t1, b1 = 2 * i + 1, 2 * i + 2, 2 * i + 3, 2 * i + 4
    n0, n1 = i + 1, i + 2
    lines.append(f"f {t0}/{t0}/{n0} {b0}/{b0}/{n0} {b1}/{b1}/{n1}")
    lines.append(f"f {t0}/{t0}/{n0} {b1}/{b1}/{n1} {t1}/{t1}/{n1}")
with open(os.path.join(out, "SM_WaCaPrecipCylinder.obj"), "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")

# --- the rain sound -----------------------------------------------------------------------------------------------
RATE, SECONDS, FADE = 44100, 12.0, 1.5
rng = np.random.default_rng(7)
n = int(RATE * (SECONDS + FADE))


def lowpass(x, cutoff):
    a = math.exp(-2 * math.pi * cutoff / RATE)
    y = np.empty_like(x)
    acc = 0.0
    for i in range(len(x)):                       # one-pole: fine for a one-off generator
        acc = (1 - a) * x[i] + a * acc
        y[i] = acc
    return y


white = rng.standard_normal(n)
hiss = white - lowpass(white, 1800)               # the steady high "shhh" of rain
body = lowpass(rng.standard_normal(n), 600)       # the low rumble on leaves / ground
body /= np.max(np.abs(body))
# drops: short decaying ticks at random times, random pitch
drops = np.zeros(n)
for t in rng.uniform(0, n - 2000, int(SECONDS * 140)):
    i = int(t)
    length = int(rng.uniform(150, 900))
    k = np.arange(length)
    f = rng.uniform(1500, 5000)
    drops[i:i + length] += np.sin(2 * np.pi * f * k / RATE) * np.exp(-k / (length / 5)) * rng.uniform(0.05, 0.35)
mix = 0.55 * hiss / np.max(np.abs(hiss)) + 0.35 * body + drops
# seamless loop: the extra FADE seconds at the end crossfade into the start
loop = mix[: int(RATE * SECONDS)].copy()
fl = int(RATE * FADE)
ramp = np.linspace(0, 1, fl)
loop[:fl] = loop[:fl] * ramp + mix[int(RATE * SECONDS): int(RATE * SECONDS) + fl] * (1 - ramp)
loop = loop / np.max(np.abs(loop)) * 0.7
with wave.open(os.path.join(out, "SW_WaCaRainLoop.wav"), "wb") as w:
    w.setnchannels(1)
    w.setsampwidth(2)
    w.setframerate(RATE)
    w.writeframes((loop * 32767).astype("<i2").tobytes())
print("sources ->", os.path.abspath(out))
